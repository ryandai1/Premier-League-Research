"""Build repository overview graphics from frozen executed results; no model training."""

from pathlib import Path
import json
import numpy as np
import pandas as pd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from experiments.catalog import run_path

ROOT = Path(__file__).resolve().parents[1]


def main():
    OUT = ROOT / "results/profile"
    OUT.mkdir(exist_ok=True)
    RUNS = {
        "Experiment 1 original": run_path("experiment_1_original"),
        "Experiment 1 rerun": run_path("experiment_1_verification"),
        "Experiment 2 rerun": run_path("experiment_2_current"),
    }
    models = [
        "arsenal_mlp",
        "league_mlp",
        "league_to_arsenal_mlp",
        "league_logistic",
        "arsenal_logistic",
        "league_prior",
    ]
    labels = [
        "Arsenal-only MLP",
        "League-wide MLP",
        "League → Arsenal MLP",
        "League logistic",
        "Arsenal logistic",
        "League class prior",
    ]
    plt.rcParams.update(
        {
            "font.size": 11,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "figure.facecolor": "white",
        }
    )
    fig, ax = plt.subplots(figsize=(11, 6))
    frames = []
    for i, ((label, path), color, hatch) in enumerate(
        zip(RUNS.items(), ["#236B8E", "#B78126", "#676767"], ["", "//", ".."])
    ):
        m = (
            pd.read_csv(path / "metrics.csv")
            .query("split=='test' and population=='Arsenal'")
            .set_index("model")
            .loc[models]
        )
        assert (m.n == 75).all()
        frames.append(m.reset_index().assign(run=label))
        ax.barh(
            np.arange(len(models)) + (i - 1) * 0.22,
            m.log_loss,
            height=0.21,
            color=color,
            hatch=hatch,
            label=label,
        )
    for y, v in enumerate(m.log_loss):
        ax.text(v + 0.012, y, f"{v:.6f}", va="center", fontsize=10)
    ax.set_yticks(np.arange(len(models)), labels)
    ax.invert_yaxis()
    ax.set(xlim=(0, 1.23), xlabel="Arsenal test log loss — lower is better")
    ax.legend(
        loc="lower center",
        bbox_to_anchor=(0.5, 1.01),
        ncol=3,
        frameon=False,
        fontsize=10,
    )
    fig.suptitle(
        "Arsenal test results across all three executions", fontsize=16, y=0.98
    )
    fig.text(
        0.5,
        0.015,
        "75 identical fixtures · 2024/25–2025/26 · Same scores across runs · Test previously inspected",
        ha="center",
        fontsize=10,
    )
    fig.tight_layout(rect=(0, 0.05, 1, 0.92))
    fig.savefig(OUT / "test_results.png", dpi=160)
    plt.close(fig)
    pd.concat(frames, ignore_index=True).to_csv(OUT / "test_results.csv", index=False)
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.8), sharey=True)
    r = RUNS["Experiment 2 rerun"]
    summary = pd.read_csv(r / "training_summary.csv").set_index("model")
    for ax, model, title in zip(
        axes,
        models[:3],
        [
            "1. Arsenal-only baseline",
            "2. Independent league challenger",
            "3. Optional Arsenal specialization",
        ],
    ):
        h = pd.read_csv(r / f"{model}_history.csv")
        best = int(summary.loc[model, "best_epoch"])
        ax.plot(
            h.epoch,
            h.training_log_loss,
            color="#236B8E",
            label="Training (dropout active)",
        )
        ax.plot(
            h.epoch,
            h.validation_arsenal_log_loss,
            color="#B78126",
            linestyle="--",
            label="Arsenal validation",
        )
        ax.axvline(best, color="#333333", linestyle=":", label=f"Best epoch: {best}")
        ax.set(title=title, xlabel="Epoch", ylim=(0.77, 1.12))
        ax.legend(fontsize=8, loc="upper right")
    axes[0].set_ylabel("Cross-entropy loss")
    fig.suptitle("Experiment 2: 100 + 100 + 21 completed epochs", fontsize=16)
    fig.text(
        0.5,
        0.02,
        "Same 74 Arsenal validation fixtures in every panel. Training populations differ. Fixed seed 42; test previously inspected.",
        ha="center",
        fontsize=10,
    )
    fig.tight_layout(rect=(0, 0.07, 1, 0.93))
    fig.savefig(OUT / "learning_curves.png", dpi=160)
    plt.close(fig)
    (OUT / "README.md").write_text(
        """# Project overview figures

    Generated by `python -m experiments.profile_figures` from frozen saved metrics and epoch histories. No training occurs during figure generation.

    - `test_results.png`: six models across the original experiment 1, its fresh rerun, and latest experiment 2. Exact numbers: `test_results.csv`.
    - `learning_curves.png`: latest experiment 2, in actual training order, on a common loss scale. Validation uses the same 74 Arsenal fixtures; training populations differ. The frozen validation comparison occurs between panels 2 and 3.

    These are reproducibility reruns after test inspection, not independent confirmatory experiments. Source directories are specified in the plotting script. All values come from executed outputs.
    """
    )


if __name__ == "__main__":
    main()
